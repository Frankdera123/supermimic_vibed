"""Generate all PADA-0 direction sets with full provenance (CPU/GPU, no simulator).

Outputs (under --out_dir):
  probe_random.pt   (S_probe, K_probe, H, 29)  per-start iid random unit dirs
  probe_policy.pt   (S_probe, K_probe, H, 29)  real diag-pair delta dirs, 8 gen
                    frames per probe clip, assigned to both starts of the clip
  eval_random.pt    (S_eval, K_eval, H, 29)    fresh seeds
  eval_pol_seen.pt  (S_eval, K_eval, H, 29)    4 of the TRAIN policy dirs
  eval_pol_B.pt     (S_eval, K_eval, H, 29)    online_B0@2300 pair deltas
  eval_pol_C.pt     (S_eval, K_eval, H, 29)    online_B2@2100 pair deltas

Policy-shift directions follow the CRGF delta convention: delta_a_t =
pi_new(o_t) - pi_old(o_t), both policies teacher-forced on the shared obs
sequence generated by pi_old closed-loop in the designated WM (OPEN-LOOP,
shared-observation deltas -- never claim closed-loop validation).

Random directions: crgf.random_dir_seqs (per-step unit dirs, seeded).
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

_HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE.parent))
import pada_bridge as bridge  # noqa: E402

bridge.import_stack()
bridge.fix_paths()

import torch  # noqa: E402

from supermimic.crgf import Protocol, normalize_dir_seqs, random_dir_seqs  # noqa: E402
from supermimic.mdp import normalize_xi  # noqa: E402


@torch.no_grad()
def delta_dirs_at_frames(pair, world, gen_frames: list[int], H: int, device: str):
    """One delta direction per generation frame (teacher-forced shared-obs)."""
    motion, mdp, proto = world["motion"], world["mdp"], world["proto"]
    pi_old, pi_new, wm = pair["pi_old"], pair["pi_new"], pair["wm"]
    hist = pair["hist"]
    dev = device
    f0_all = torch.tensor(gen_frames, device=dev)
    N = len(gen_frames)
    S = motion.ref_state(f0_all)
    xi = torch.zeros(N, 33, device=dev)
    xi[:, 0] = 1.0
    xi_n = normalize_xi(xi)
    obs0 = proto.obs(S, torch.zeros(N, 29, device=dev), xi, f0_all)
    o_hist = obs0.unsqueeze(1).expand(-1, hist, -1).contiguous()
    a_olds, a_news, f = [], [], f0_all
    for _ in range(H):
        g_goal = proto.actor_goal(f, S)
        a_o = pi_old(o_hist, g_goal)
        a_n = pi_new(o_hist, g_goal)
        a_olds.append(a_o)
        a_news.append(a_n)
        S = proto.wm_step(wm, S, torch.clamp(a_o, -20, 20), xi_n)
        f1 = f + 1
        o1 = proto.obs(S, a_o, xi, f1)
        o_hist = torch.cat((o_hist[:, 1:], o1.unsqueeze(1)), 1)
        f = f1
    a_old = torch.stack(a_olds, 1).cpu()   # (N, H, 29)
    a_new = torch.stack(a_news, 1).cpu()
    delta = a_new - a_old
    norms = delta.reshape(N, -1).norm(dim=-1)
    return normalize_dir_seqs(delta), norms, a_old, a_new


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out_dir", type=Path, required=True)
    ap.add_argument("--probe_clips", type=int, default=6)
    ap.add_argument("--eval_clips", type=int, default=3)
    ap.add_argument("--frames_per_clip", type=int, default=2)
    ap.add_argument("--k_probe", type=int, default=8)
    ap.add_argument("--k_eval", type=int, default=4)
    ap.add_argument("--horizon", type=int, default=32)
    ap.add_argument("--seed", type=int, default=2300)
    ap.add_argument("--device", default="cpu")
    ap.add_argument("--pairs", default="train=online_B0:2100,unseen_B=online_B0:2300,unseen_C=online_B2:2100",
                    help="comma list name=run:iteration")
    ap.add_argument("--max_minutes", type=float, default=14.0)
    args = ap.parse_args()
    dev = args.device
    t0 = time.time()
    args.out_dir.mkdir(parents=True, exist_ok=True)

    pair_specs = {}
    for spec in args.pairs.split(","):
        name, ref = spec.split("=")
        run, it = ref.split(":")
        pair_specs[name] = (run, int(it))
    pairs = {name: bridge.load_pair_bundle(run, it, device=dev)
             for name, (run, it) in pair_specs.items()}

    world = bridge.setup_world(device=dev, pair=pairs["train"])
    motion = world["motion"]
    H = args.horizon

    probe_clips = bridge.select_starts(motion, args.probe_clips, args.frames_per_clip,
                                       seed=args.seed)
    # eval clips must be disjoint from probe clips: continue the same seeded
    # permutation so clip reuse is impossible by construction
    import torch as _t
    g_all = _t.Generator().manual_seed(args.seed)
    all_order = _t.randperm(len(motion.names), generator=g_all)
    n_probe_clips = args.probe_clips
    eval_clip_ids = all_order[n_probe_clips:n_probe_clips + args.eval_clips].sort().values.tolist()
    assert not (set(eval_clip_ids) & set(s["clip"] for s in probe_clips)), "clip overlap"
    g2 = _t.Generator().manual_seed(args.seed + 1)
    eval_clips = []
    for c in eval_clip_ids:
        s0, s1 = int(motion.clip_start[c]), int(motion.clip_end[c])
        hi = max(s0 + 1, s1 - 64 - 1)
        frames = s0 + 1 + _t.randperm(hi - s0 - 1, generator=g2)[:args.frames_per_clip].sort().values
        eval_clips.append({"clip": c, "clip_name": motion.names[c], "frames": frames.tolist()})
    # flat per-start lists (one entry per simulated start)
    probe_starts, eval_starts = [], []
    for s in probe_clips:
        for f in s["frames"]:
            probe_starts.append({"clip": s["clip"], "clip_name": s["clip_name"], "frame": int(f)})
    for s in eval_clips:
        for f in s["frames"]:
            eval_starts.append({"clip": s["clip"], "clip_name": s["clip_name"], "frame": int(f)})

    meta = {
        "created": time.strftime("%Y-%m-%d %H:%M:%S"),
        "seed": args.seed, "horizon": H,
        "probe_clips": probe_clips, "eval_clips": eval_clips,
        "probe_starts": probe_starts, "eval_starts": eval_starts,
        "pairs": {k: {"run": v["run"], "iteration": v["iteration"], "path": v["path"],
                      "sha256": v["sha256"],
                      "pi_updates": [v["pi_updates_before"], v["pi_updates_after"]],
                      "pi_param_l2_diff": v["pi_param_l2_diff"]}
                  for k, v in pairs.items()},
        "motion_dir": world["motion_dir"],
        "convention": "unit dirs over flattened (H,29); policy dirs are OPEN-LOOP "
                      "shared-obs deltas pi_new(o)-pi_old(o)",
    }

    def gen_frames_for_clip(clip, n, gen, used=()):
        s0, s1 = int(motion.clip_start[clip]), int(motion.clip_end[clip])
        hi = max(s0 + 1, s1 - H - 1)
        cand = s0 + 1 + _t.randperm(hi - s0 - 1, generator=gen)
        frames = []
        for f in cand.tolist():
            if f in used:
                continue
            frames.append(f)
            if len(frames) == n:
                break
        return frames

    # ---- probe random: (S, K, H, 29), fresh seed per start ----
    S_p, Kp = len(probe_starts), args.k_probe
    probe_random = torch.zeros(S_p, Kp, H, 29)
    for si in range(S_p):
        probe_random[si] = random_dir_seqs(Kp, H, 29, seed=args.seed + 100 + si)

    # ---- probe policy: 8 gen frames per probe clip; assigned to its starts ----
    probe_policy = torch.zeros(S_p, Kp, H, 29)
    pol_meta = []
    gen_g = _t.Generator().manual_seed(args.seed + 2)
    for ci, s in enumerate(probe_clips):
        used = set(s["frames"])
        frames = gen_frames_for_clip(s["clip"], Kp, gen_g, used=used)
        dirs, norms, a_old, a_new = delta_dirs_at_frames(pairs["train"], world, frames, H, dev)
        slots = [si for si, ps in enumerate(probe_starts) if ps["clip"] == s["clip"]]
        for si in slots:
            probe_policy[si] = dirs
        pol_meta.append({"clip": s["clip_name"], "gen_frames": frames,
                         "delta_norms": norms.tolist(),
                         "assigned_starts": slots,
                         "degenerate_skipped": Kp - len(frames)})
    meta["probe_policy_gen"] = pol_meta

    # ---- eval random ----
    S_e, Ke = len(eval_starts), args.k_eval
    eval_random = torch.zeros(S_e, Ke, H, 29)
    for si in range(S_e):
        eval_random[si] = random_dir_seqs(Ke, H, 29, seed=args.seed + 200 + si)

    # ---- eval pol_seen: 4 of the training policy vectors (seeded), shared ----
    flat = probe_policy.reshape(-1, H, 29)
    pick = _t.randperm(flat.shape[0], generator=_t.Generator().manual_seed(args.seed + 3))[:Ke]
    eval_seen = flat[pick].unsqueeze(0).expand(S_e, Ke, H, 29).clone()
    meta["pol_seen_pick"] = pick.tolist()

    # ---- eval pol_unseen_B / C: 4 gen frames per eval clip, shared per clip ----
    unseen = {}
    for name in ("unseen_B", "unseen_C"):
        out = torch.zeros(S_e, Ke, H, 29)
        umeta = []
        gen_g2 = _t.Generator().manual_seed(args.seed + 4 + ("B" == name))
        for s in eval_clips:
            frames = gen_frames_for_clip(s["clip"], Ke, gen_g2)
            dirs, norms, _, _ = delta_dirs_at_frames(pairs[name], world, frames, H, dev)
            slots = [si for si, es in enumerate(eval_starts) if es["clip"] == s["clip"]]
            for si in slots:
                out[si] = dirs
            umeta.append({"clip": s["clip_name"], "gen_frames": frames,
                          "delta_norms": norms.tolist()})
        unseen[name] = out
        meta[f"{name}_gen"] = umeta

    for name, tens in [("probe_random", probe_random), ("probe_policy", probe_policy),
                       ("eval_random", eval_random), ("eval_pol_seen", eval_seen),
                       ("eval_pol_B", unseen["unseen_B"]), ("eval_pol_C", unseen["unseen_C"])]:
        flatn = tens.reshape(tens.shape[0], tens.shape[1], -1).norm(dim=-1)
        assert torch.allclose(flatn, torch.ones_like(flatn), atol=1e-4), name
        _t.save({"dirs": tens, "meta": meta}, args.out_dir / f"{name}.pt")
    meta["elapsed_s"] = round(time.time() - t0, 1)
    with open(args.out_dir / "directions_meta.json", "w") as fh:
        json.dump(meta, fh, indent=1, default=str)
    print(json.dumps({"out_dir": str(args.out_dir), "probe_starts": S_p, "eval_starts": S_e,
                      "k_probe": Kp, "k_eval": Ke, "H": H,
                      "elapsed_s": meta["elapsed_s"]}, indent=1))


if __name__ == "__main__":
    main()
